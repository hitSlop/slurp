// Keeps the pricing table in the repository README identical to the one on the website: both come from src/lib/pricing.mjs.
//   node apps/site/scripts/readme-pricing.mjs          rewrite the table between the markers in README.md
//   node apps/site/scripts/readme-pricing.mjs --check  exit 1 if README.md is out of date (used in CI)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { volumes, tools, money, count, asOf, assumptions as a, rangeFrom, roughly } from '../src/lib/pricing.mjs';

const readme = fileURLToPath(new URL('../../../README.md', import.meta.url));
const START = '<!-- pricing:start (generated by apps/site/scripts/readme-pricing.mjs) -->';
const END = '<!-- pricing:end -->';

const cell = (tool, n) => {
  const c = tool.cost(n);
  const range = tool.range && n >= rangeFrom ? tool.range(n) : null;
  const text = range ? `${money(roughly(range[0]))} to ${money(roughly(range[1]))}` : c === null ? tool.unpublished : money(c);
  return tool.self ? `**${text}**` : text;
};
const name = (tool) => {
  const href = tool.self ? 'docs/self-hosting.md#costs-and-limits' : tool.url;
  return `[${tool.self ? `**${tool.name}**` : tool.name}](${href})`;
};

export function table() {
  const header = `| Monthly USD, by events per month | ${volumes.map(count).join(' | ')} |`;
  const rule = `|---|${volumes.map(() => '--:').join('|')}|`;
  const rows = tools.map((t) => `| ${name(t)} | ${volumes.map((n) => cell(t, n)).join(' | ')} |`);
  return [
    header, rule, ...rows, '',
    `*Vendor prices read from their public pricing pages on ${asOf}; they change, so check before deciding. Mixpanel is yearly billing. Amplitude does not publish paid event prices, and Mixpanel and OpenPanel direct high volumes to sales.*`,
    '',
    `The Slurp row is the Cloudflare bill for running your own Worker, not a Slurp fee: ${a.eventsPerRequest} events per request, about ${a.compressedBytesPerEvent} bytes stored per event, ${a.retentionMonths} months of archives kept, at Cloudflare's list prices (the Workers Free plan covers you until about ${(a.freeRequestsPerDay * a.freeHeadroom / 1000).toFixed(0)}K requests a day). The 1B and 10B figures are ranges, extrapolated from load tests of about ${a.eventsPerSecondPerSource.toLocaleString('en-US')} events a second per source, not months of running those volumes; about two thirds of the bill is R2 storage, so event size and retention matter most. Details: [docs/self-hosting.md](docs/self-hosting.md#costs-and-limits).`,
  ].join('\n');
}

const current = readFileSync(readme, 'utf8');
const from = current.indexOf(START);
const to = current.indexOf(END);
if (from < 0 || to < from) throw new Error('README.md needs the pricing markers');
const next = `${current.slice(0, from)}${START}\n${table()}\n${current.slice(to)}`;
if (process.argv.includes('--check')) {
  if (next !== current) {
    console.error('README.md pricing table is out of date: run node apps/site/scripts/readme-pricing.mjs');
    process.exit(1);
  }
} else if (next !== current) {
  writeFileSync(readme, next);
}
