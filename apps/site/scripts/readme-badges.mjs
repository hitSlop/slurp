// Keeps the "works with" badges in the repository README identical to the chips on the website: both come from the
// `worksWith` list in src/lib/connections.ts.
//   node apps/site/scripts/readme-badges.mjs          rewrite the badges between the markers in README.md
//   node apps/site/scripts/readme-badges.mjs --check  exit 1 if README.md is out of date (used in CI)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { worksWith } from '../src/lib/connections.ts';

const readme = fileURLToPath(new URL('../../../README.md', import.meta.url));
const logoDir = new URL('../../../packages/web-shared/logos/', import.meta.url);
const START = '<!-- sdk-badges:start (generated by apps/site/scripts/readme-badges.mjs) -->';
const END = '<!-- sdk-badges:end -->';

// shields.io static badge path: a hyphen is written -- and an underscore __; spaces are encoded.
const part = (text) => encodeURIComponent(text.replaceAll('-', '--').replaceAll('_', '__'));

/** The badge image URL. A Simple Icons slug gives the logo; tools without one (React Native, Segment) embed their SVG from packages/web-shared/logos. */
export function badgeUrl(w) {
  const params = new URLSearchParams({ style: 'flat-square', labelColor: '1f2327' });
  if (w.slug) {
    params.set('logo', w.slug);
    if (w.logoColor) params.set('logoColor', w.logoColor);
  } else if (w.logo) {
    const svg = readFileSync(new URL(`${w.logo}.svg`, logoDir), 'utf8');
    params.set('logo', `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`);
  }
  return `https://img.shields.io/badge/${part(w.name)}-${part(w.note)}-${w.color}?${params}`;
}

const groups = [['capture', 'Capture from'], ['keep', 'Keep using'], ['soon', 'Coming']];
// GitHub fetches README images through a proxy that refuses very long URLs: a badge whose logo is an inline SVG can then show as a broken
// image on github.com while still working when opened directly. Prefer a Simple Icons `slug` for the README.
export const MAX_BADGE_URL = 3000;

export function block() {
  const rows = groups.map(([id, label]) => {
    const images = worksWith.filter((w) => w.group === id).map((w) => `<img src="${badgeUrl(w)}" alt="${w.name}: ${w.note}">`);
    return `  <b>${label}</b>&nbsp; ${images.join('\n  ')}`;
  });
  return [
    '<p align="center">',
    rows.join('<br>\n'),
    '</p>',
    '<p align="center"><sub>Logos are trademarks of their owners, used only to show compatibility.</sub></p>',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const current = readFileSync(readme, 'utf8');
  const from = current.indexOf(START);
  const to = current.indexOf(END);
  if (from < 0 || to < from) throw new Error('README.md needs the sdk-badges markers');
  const next = `${current.slice(0, from)}${START}\n${block()}\n${current.slice(to)}`;
  for (const w of worksWith) {
    const url = badgeUrl(w);
    if (url.length > MAX_BADGE_URL) {
      console.error(`${w.name}: its badge URL is ${url.length} characters (limit ${MAX_BADGE_URL}); GitHub would show it broken. Give it a Simple Icons slug.`);
      process.exit(1);
    }
  }
  if (process.argv.includes('--check')) {
    if (next !== current) {
      console.error('README.md badges are out of date: run node apps/site/scripts/readme-badges.mjs');
      process.exit(1);
    }
  } else if (next !== current) {
    writeFileSync(readme, next);
  }
}
